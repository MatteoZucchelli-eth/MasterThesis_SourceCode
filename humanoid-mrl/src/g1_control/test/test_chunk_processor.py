"""Unit tests for the VLA ChunkProcessor (require the G1 URDF)."""

import numpy as np
import pytest

from g1_control.vla.postprocess import ChunkProcessor
from g1_definitions import definitions


@pytest.fixture
def processor(robot_model):
    default_upper = robot_model.get_initial_upper_body_pose()
    return ChunkProcessor(robot_model, default_upper, ood_scorer=None)


def test_eef_9d_chunk_shapes(processor, robot_model):
    n_act = len(robot_model.get_body_actuated_joint_indices())
    n_upper = len(robot_model.get_joint_group_indices("upper_body"))
    joint_pos = np.zeros(n_act)
    chunk = np.tile(processor.default_upper_body_pose, (5, 1))
    assert chunk.shape == (5, n_upper)
    assert processor.eef_9d_chunk(joint_pos, chunk).shape == (5, 9)


def test_smooth_constant_chunk_is_unchanged(processor, robot_model):
    n_act = len(robot_model.get_body_actuated_joint_indices())
    joint_pos = np.zeros(n_act)
    base = processor.default_upper_body_pose
    chunk = np.tile(base, (8, 1))
    out = processor.smooth({"upper_body_joint_chunk": chunk.copy()}, joint_pos)[
        "upper_body_joint_chunk"
    ]
    assert np.allclose(out, chunk)


def test_smooth_reduces_single_spike(processor, robot_model):
    n_act = len(robot_model.get_body_actuated_joint_indices())
    joint_pos = np.zeros(n_act)
    # Force a non-zero radius, independent of the deployed default.
    processor._smooth_radius = 2
    base = processor.default_upper_body_pose
    chunk = np.tile(base, (8, 1))
    chunk[4] = base + 1.0  # a one-step spike
    out = processor.smooth({"upper_body_joint_chunk": chunk.copy()}, joint_pos)[
        "upper_body_joint_chunk"
    ]
    assert np.max(np.abs(out[4] - base)) < 1.0


def test_smooth_radius_is_a_constructor_argument(robot_model):
    """smooth_radius is configurable via the constructor (vla_config.yaml)."""
    default_upper = robot_model.get_initial_upper_body_pose()
    n_act = len(robot_model.get_body_actuated_joint_indices())
    joint_pos = np.zeros(n_act)
    base = default_upper
    chunk = np.tile(base, (8, 1))
    chunk[4] = base + 1.0

    off = ChunkProcessor(robot_model, default_upper, ood_scorer=None, smooth_radius=0)
    out = off.smooth({"upper_body_joint_chunk": chunk.copy()}, joint_pos)[
        "upper_body_joint_chunk"
    ]
    assert np.allclose(out, chunk)  # radius 0 disables the filter entirely

    on = ChunkProcessor(robot_model, default_upper, ood_scorer=None, smooth_radius=3)
    out = on.smooth({"upper_body_joint_chunk": chunk.copy()}, joint_pos)[
        "upper_body_joint_chunk"
    ]
    assert np.max(np.abs(out[4] - base)) < 1.0


def test_process_ik_output_shape(processor, robot_model):
    n_act = len(robot_model.get_body_actuated_joint_indices())
    n_upper = len(robot_model.get_joint_group_indices("upper_body"))
    # Use tip poses generated by FK of the default pose so IK is well-posed.
    joint_pos = np.zeros(n_act)
    chunk = np.tile(processor.default_upper_body_pose, (3, 1))
    right = processor.eef_9d_chunk(joint_pos, chunk)
    out = processor.process_ik({definitions.RIGHT_EEF_KEY: right}, joint_pos)
    assert out["upper_body_joint_chunk"].shape == (3, n_upper)


def test_process_ik_holds_the_left_arm_at_its_default(processor, robot_model):
    """The policy predicts the tip only, so the left arm must not drift."""
    n_act = len(robot_model.get_body_actuated_joint_indices())
    joint_pos = np.zeros(n_act)
    default_upper = processor.default_upper_body_pose
    chunk = np.tile(default_upper, (3, 1))
    right = processor.eef_9d_chunk(joint_pos, chunk)

    out = processor.process_ik({definitions.RIGHT_EEF_KEY: right}, joint_pos)

    rel_left = robot_model.get_relative_group_indices("left_arm", "upper_body")
    for step in out["upper_body_joint_chunk"]:
        assert np.allclose(step[rel_left], default_upper[rel_left])


def test_state_jacobian_matches_finite_difference(processor, robot_model):
    n_act = len(robot_model.get_body_actuated_joint_indices())
    joint_pos = np.zeros(n_act)
    step = processor.default_upper_body_pose.copy()

    J = processor._state_jacobian_for_step(step, joint_pos)
    state = processor._predict_state_for_step(step, joint_pos)
    n_state = state.shape[0]
    n_upper = step.shape[0]
    assert n_state == definitions.STATE_DIM
    assert J.shape == (n_state, n_upper)

    eps = 1e-5
    for j in range(n_upper):
        d = np.zeros(n_upper)
        d[j] = eps
        plus = processor._predict_state_for_step(step + d, joint_pos)
        minus = processor._predict_state_for_step(step - d, joint_pos)
        fd = (plus - minus) / (2 * eps)
        assert np.allclose(J[:, j], fd, atol=1e-3), f"column {j} mismatch"


